
const express = require("express");

const Agent = require("../models/Agent");
const Activity = require("../models/Activity");

const {
  getLeaderboard
} = require("../utils/leaderboard");

const router = express.Router();

const VALID_PERIODS = ["daily", "weekly", "monthly"];
const LEADERBOARD_LIMIT = 100;
const RECENT_ACTIVITY_LIMIT = 8;

/* =========================================================
   DASHBOARD
   GET /
========================================================= */

router.get("/", async (req, res, next) => {
  try {
    // Require login before showing dashboard data.
    if (!req.session?.adminId) {
      return res.redirect("/login");
    }

    const requestedPeriod =
      typeof req.query.period === "string"
        ? req.query.period.trim().toLowerCase()
        : "daily";

    const period = VALID_PERIODS.includes(requestedPeriod)
      ? requestedPeriod
      : "daily";

    const [
      agentsCount,
      activeCount,
      leaderboard
    ] = await Promise.all([
      Agent.countDocuments(),

      Agent.countDocuments({ active: true }),

      getLeaderboard(period, LEADERBOARD_LIMIT)
    ]);

    const rows = Array.isArray(leaderboard?.rows)
      ? leaderboard.rows
      : [];

    // Keep the rank and badge values generated by leaderboard.js.
    const normalizedRows = rows.map((row, index) => {
      const points = Number(row.points);

      return {
        ...row,
        points: Number.isFinite(points) ? points : 0,
        rank: Number.isFinite(Number(row.rank))
          ? Number(row.rank)
          : index + 1
      };
    });

    const totalPoints = normalizedRows.reduce(
      (sum, row) => sum + row.points,
      0
    );

    const podium = normalizedRows.slice(0, 3);

    // Recent activities are independent of leaderboard period here.
    // Add an occurredAt date range if you want period-specific activity.
    const recentActivities = await Activity.find()
      .sort({
        occurredAt: -1,
        createdAt: -1,
        _id: -1
      })
      .limit(RECENT_ACTIVITY_LIMIT)
      .populate("agent", "name email team")
      .lean();

    return res.render("dashboard", {
      title: "Performance Center | Gyansify",

      period,

      agentsCount,
      activeCount,
      inactiveCount: Math.max(0, agentsCount - activeCount),

      totalPoints,

      leaderboard: normalizedRows,
      podium,
      recentActivities,

      periodStart: leaderboard?.start || null
    });
  } catch (error) {
    return next(error);
  }
});

module.exports = router;
